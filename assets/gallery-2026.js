    function parseDateFromName(fileName) {
      const stem = fileName.replace(/\.[^.]+$/, '');
      const patterns = [
        /^(\d{4})(\d{2})(\d{2})_(\d{2})(\d{2})(\d{2})$/,
        /(?:^|[_-])(\d{4})(\d{2})(\d{2})_(\d{2})(\d{2})(\d{2})(?:\(\d+\))?(?:$|[_-])/,
        /(?:^|[_-])(\d{4})[-_](\d{2})[-_](\d{2})[-_ T](\d{2})[-_](\d{2})[-_](\d{2})(?:$|[_-])/,
        /IMG_(\d{4})(\d{2})(\d{2})_(\d{2})(\d{2})(\d{2})/,
        /^(signal)-(\d{4})-(\d{2})-(\d{2})-(\d{2})-(\d{2})-(\d{2})/,
      ];

      for (const pattern of patterns) {
        const ts = stem.match(pattern);
        if (!ts) continue;
        if (pattern.source.includes('signal')) {
          return new Date(`${ts[2]}-${ts[3]}-${ts[4]}T${ts[5]}:${ts[6]}:${ts[7]}`);
        }
        return new Date(`${ts[1]}-${ts[2]}-${ts[3]}T${ts[4]}:${ts[5]}:${ts[6]}`);
      }
      return null;
    }

